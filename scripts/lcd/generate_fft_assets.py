"""Generate the quarter-wave coefficient ROM and independent FFT test vectors.

Only Python standard library is required for RTL/hex assets. The optional
--vectors mode also uses NumPy as a floating-point accuracy cross-check.
The generated ROM embeds all initial data; no absolute or runtime file path.
"""
from pathlib import Path
import argparse
import json
import math

ROOT=Path(__file__).resolve().parents[2]
ASSETS=ROOT/'assets/lcd_ui'
ASSETS.mkdir(parents=True,exist_ok=True)
N=1024
quarter=[int(math.floor(math.sin(math.pi*k/512)*32768+0.5)) for k in range(257)]

def cosine(phase):
    p=(phase+256)&1023
    index=256-(p&255) if p&256 else p&255
    return -quarter[index] if p&512 else quarter[index]

words=quarter+[0]*(1024-len(quarter))
params=[]
for i in range(64):
    value=sum(words[16*i+j] << (16*j) for j in range(16))
    params.append("        .INIT_RAM_%02X(256'h%064x)"%(i,value))
rtl='''/**
 * Shared FFT/Hann coefficient ROM: 257 quarter-wave UQ1.15 magnitudes in one
 * initialized GW5A SDPB. Reconstruction returns cosine as signed SQ2.15,
 * 17 bits, including exact +1/-1 (32768/-32768). Phase is an integer0..1023.
 * clk/rst_n are clk_sys/rst_sys_n. en accepts one phase on the rising edge;
 * coefficient appears after that edge (one synchronous RAM read), then holds.
 * No DSP, runtime file dependency or replicated per-stage ROM.
 * Generated by scripts/lcd/generate_fft_assets.py; sim/synthesis use same IP.
 */
module lcd_fft_coeff_rom
(
    input clk,
    input rst_n,
    input en,
    input [9:0] phase,
    output signed [16:0] coefficient
);
    wire [9:0] sine_phase = phase + 10'd256;
    wire [8:0] address = sine_phase[8] ? (9'd256 - {1'b0,sine_phase[7:0]}) : {1'b0,sine_phase[7:0]};
    wire [31:0] data;
    reg negative_r;
    assign coefficient = negative_r ? -$signed({1'b0,data[15:0]}) : $signed({1'b0,data[15:0]});
    always @(posedge clk or negedge rst_n)
    begin
        if (!rst_n) negative_r <= 1'b0;
        else if (en) negative_r <= sine_phase[9];
    end
    SDPB #(
        .READ_MODE(1'b0), .BIT_WIDTH_0(16), .BIT_WIDTH_1(16),
        .RESET_MODE("ASYNC"), .BLK_SEL_0(3'b000), .BLK_SEL_1(3'b000),
'''+',\n'.join(params)+'''
    ) sdpb_u (
        .CLKA(clk), .CLKB(clk), .CEA(1'b0), .CEB(en && rst_n), .OCE(1'b1),
        .RESET(!rst_n), .BLKSELA(3'b000), .BLKSELB(3'b000),
        .ADA(14'd0), .ADB({1'b0,address,4'b0000}), .DI(32'd0), .DO(data)
    );
endmodule
'''
(ROOT/'src/lcd_ui/lcd_fft_coeff_rom.v').write_text(rtl,encoding='utf-8')
(ASSETS/'fft_cosine.hex').write_text(''.join('%05x\n'%(cosine(k)&0x1ffff) for k in range(N)),encoding='ascii')

def reference(samples):
    # High-level in-place radix2 reference, independent of RTL FSM/RAM ports.
    def rev(n):return int(format(n,'010b')[::-1],2)
    r=[0]*N
    im=[0]*N
    for k,x in enumerate(samples):
        hann=(32768-cosine(k)+1)//2
        r[rev(k)]=(x*hann+16384)//32768
    overflow=False
    def quant(v):
        nonlocal overflow
        q=(v+32768)//65536
        if q < -32768 or q > 32767:overflow=True
        return min(32767,max(-32768,q))
    half=1
    while half<N:
        for base in range(0,N,2*half):
            for j in range(half):
                a=base+j;b=a+half
                co=cosine(j*N//(2*half));si=cosine(j*N//(2*half)-256)
                tr=r[b]*co+im[b]*si
                ti=im[b]*co-r[b]*si
                ar=r[a]*32768;ai=im[a]*32768
                r[a],im[a],r[b],im[b]=quant(ar+tr),quant(ai+ti),quant(ar-tr),quant(ai-ti)
        half*=2
    mags=[];clipped=False
    def isqrt(value):
        if value==0:return 0
        root=1 << ((value.bit_length()+1)//2)
        while True:
            new=(root+value//root)//2
            if new>=root:return root
            root=new
    for k in range(513):
        magnitude=isqrt(r[k]*r[k]+im[k]*im[k]) << (1 if k in (0,512) else 2)
        clipped |= magnitude>32768
        mags.append(min(32768,magnitude))
    return r[:513],im[:513],mags,overflow,clipped

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--vectors',action='store_true')
    args=parser.parse_args()
    if args.vectors:
        import numpy as np
        rng=np.random.RandomState(20261101)
        t=np.arange(N)
        fs=98245614/2048
        vectors=[('zero',np.zeros(N)),('dc_pos',np.full(N,0.5)),('dc_neg',np.full(N,-0.5)),
                 ('negative_full',np.full(N,-1.0)),('positive_full',np.full(N,32767/32768))]
        for k in [1,9,85,128,511,512]:
            vectors.append(('bin_'+str(k),0.75*np.cos(2*np.pi*k*t/N+0.31)))
        vectors += [('A4',0.8*np.sin(2*np.pi*440*t/fs)),('C4',0.7*np.sin(2*np.pi*261.625565*t/fs)),
            ('two_tones',0.4*np.cos(2*np.pi*9*t/N)+0.3*np.sin(2*np.pi*13*t/N)),
            ('square_full',np.where(t<512,-1.0,32767/32768)),
            ('impulse',np.where(t==512,-1.0,0.0)),('noise',rng.uniform(-1,1,N))]
        raw=[];expected=[];flags=[];report=[]
        for name,x in vectors:
            pcm=np.clip(np.floor(x*32768+0.5),-32768,32767).astype(np.int64)
            r,im,mag,ov,cl=reference([int(q) for q in pcm])
            exact=np.fft.rfft(pcm*(0.5-0.5*np.cos(2*np.pi*t/N)))/N
            error=float(max(np.max(np.abs(np.array(r)-exact.real)),np.max(np.abs(np.array(im)-exact.imag))))
            assert error<16,(name,error)
            raw.extend(int(q)&65535 for q in pcm)
            expected.extend((mag[k]<<32)|((im[k]&65535)<<16)|(r[k]&65535) for k in range(513))
            flags.append((int(cl)<<1)|int(ov))
            report.append(dict(name=name,max_complex_code_error=error,overflow=bool(ov),amplitude_clipped=bool(cl),peak_bin=int(np.argmax(mag))))
        (ASSETS/'fft_input.hex').write_text(''.join('%04x\n'%x for x in raw),encoding='ascii')
        (ASSETS/'fft_expected.hex').write_text(''.join('%012x\n'%x for x in expected),encoding='ascii')
        (ASSETS/'fft_flags.hex').write_text(''.join('%x\n'%x for x in flags),encoding='ascii')
        (ASSETS/'fft_reference.json').write_text(json.dumps(dict(count=len(vectors),fs=fs,vectors=report),indent=2),encoding='utf-8')
        print('Generated',len(vectors),'vectors; max error',max(x['max_complex_code_error'] for x in report),'PCM-code LSB vs NumPy FFT.')
    else:print('Generated shared quarter-wave ROM and 1024 cosine checks.')
